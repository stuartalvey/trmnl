const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const code = fs.readFileSync(__dirname + '/transform.js', 'utf8');
const keys = ['pacers', 'colts', 'purdue_football', 'purdue_basketball', 'butler_basketball'];
const fixtures = JSON.parse(fs.readFileSync(__dirname + '/test-schedules.json', 'utf8'));
const nowMs = Date.parse('2026-11-09T15:00:00Z');
function normalize(feeds) { return JSON.parse(JSON.stringify(vm.runInNewContext(code + '; normalizeSchedules(fixtures, nowMs)', { fixtures: feeds, nowMs, Intl, Date, Set }))); }
const result = normalize(fixtures);
assert.equal(result.status, 'ok');
assert.equal(result.games.length, 9);
assert.deepEqual(keys.map(key => result.games.filter(g => g.team_key === key).length), [4, 1, 1, 2, 1]);
assert.ok(result.games.every(g => g.day >= '2026-11-09' && g.day < '2026-11-16'));
assert.equal(result.games.find(g => g.team_key === 'pacers').day, '2026-11-09');
assert.equal(result.games.find(g => g.team_key === 'pacers').time_label, '8:00 PM');
assert.equal(result.games.find(g => g.team_key === 'purdue_football').day, '2026-11-14');
assert.equal(result.games.find(g => g.team_key === 'purdue_football').time_label, '7:30 PM');
const tbdFeeds = structuredClone(fixtures);
const tbd = structuredClone(fixtures[0].events[0]);
tbd.date = tbd.competitions[0].date = '2026-11-10T00:00Z';
tbd.timeValid = tbd.competitions[0].timeValid = false;
tbd.competitions[0].status.type = { name: 'STATUS_SCHEDULED', state: 'pre', completed: false, detail: 'TBD' };
tbdFeeds[0].events = [tbd];
const tbdGame = normalize(tbdFeeds).games.find(g => g.team_key === 'pacers');
assert.equal(tbdGame.day, '2026-11-10');
assert.equal(tbdGame.time_label, 'TBD');
const failedFeeds = fixtures.slice();
failedFeeds[1] = { error: 'upstream unavailable' };
const partial = normalize(failedFeeds);
assert.equal(partial.status, 'partial');
assert.deepEqual(partial.unavailable_teams, ['Colts']);
assert.equal(partial.games.length, 8);
const cancelledFeeds = structuredClone(tbdFeeds);
cancelledFeeds[0].events[0].competitions[0].status.type.name = 'STATUS_CANCELED';
assert.equal(normalize(cancelledFeeds).games.find(g => g.team_key === 'pacers').time_label, 'Cancelled');
assert.equal(vm.runInNewContext(code + '; localDay("2026-03-09T03:30:00Z")', { Intl, Date }), '2026-03-08');
assert.equal(vm.runInNewContext(code + '; localTime("2026-03-09T03:30:00Z")', { Intl, Date }), '11:30 PM');
assert.equal(vm.runInNewContext(code + '; nextDate("2026-10-31", 7)', { Intl, Date }), '2026-11-07');
console.log('Passed: five-team schedules, seven-day range, local dates/times, DST, TBD, cancelled games, and partial feed failures.');

